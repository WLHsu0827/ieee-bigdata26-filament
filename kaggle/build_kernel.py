"""Package the ``filseg`` sources into a self-contained Kaggle script kernel.

The generated ``run.py`` embeds the package as a base64 zip, unpacks it on the
Kaggle worker, installs missing dependencies, and runs one or more command
lines. Several commands (separated by ``::``) run concurrently, one per GPU
(``CUDA_VISIBLE_DEVICES=k``), which doubles throughput on Kaggle's T4 x2.

Usage:
  python kaggle/build_kernel.py --user <kaggle-user> --name fil-r34-512 --out <staging dir> \
      [--gpu] -- -m filseg.train --out /kaggle/working/a ... :: -m filseg.train --out /kaggle/working/b ...
  kaggle kernels push -p <staging dir> [--accelerator NvidiaTeslaT4]
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TEMPLATE = r'''# Auto-generated by kaggle/build_kernel.py -- do not edit by hand.
import base64, io, os, pathlib, shutil, subprocess, sys, threading, zipfile, importlib.util

SRC = "/kaggle/working/src"
PAYLOAD = "{payload}"
COMMANDS = {commands!r}
SEQUENTIAL = {sequential!r}  # True: run the commands one after another (CPU pipelines)

os.makedirs(SRC, exist_ok=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(SRC)
if importlib.util.find_spec("segmentation_models_pytorch") is None:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "segmentation-models-pytorch"], check=True)


def pump(k, proc):
    # stream each process to the kernel log (visible live with `kaggle kernels logs`) and to procK.log
    with open(f"/kaggle/working/proc{{k}}.log", "w") as log:
        for line in proc.stdout:
            log.write(line)
            log.flush()
            print(f"[{{k}}] {{line}}", end="", flush=True)


procs, pumps, rcs = [], [], []
for k, cmd in enumerate(COMMANDS):
    env = dict(os.environ, PYTHONPATH=SRC, PYTHONUNBUFFERED="1")
    if len(COMMANDS) > 1 and not SEQUENTIAL:
        env["CUDA_VISIBLE_DEVICES"] = str(k)
    p = subprocess.Popen([sys.executable] + cmd, env=env, cwd="/kaggle/working",
                         stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
    t = threading.Thread(target=pump, args=(k, p), daemon=True)
    t.start()
    procs.append(p)
    pumps.append(t)
    if SEQUENTIAL:
        rcs.append(p.wait())
        t.join(timeout=60)
if not SEQUENTIAL:
    rcs = [p.wait() for p in procs]
for t in pumps:
    t.join(timeout=60)
print("return codes:", rcs, flush=True)
shutil.rmtree(SRC, ignore_errors=True)
for p in pathlib.Path("/kaggle/working").rglob("last.pt"):
    p.unlink()
sys.exit(max(rcs))
'''


def payload(kind: str = "full") -> str:
    """Base64 zip of the sources. ``full``: package, scripts, configs, notebook generator, evaluation
    files and small figures; ``report``: only the report sources and the figures ``main.tex`` uses
    (Kaggle rejects kernel scripts above roughly 1 MB)."""
    import re

    report = ROOT / "docs" / "report"
    if kind == "report":
        used = set(re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", (report / "main.tex").read_text()))
        files = (sorted(report.glob("*.tex")) + sorted(report.glob("*.bib")) + sorted(report.glob("*.py"))
                 + [ROOT / "docs" / "figures" / u for u in sorted(used)])
    else:
        files = (sorted((ROOT / "filseg").rglob("*.py")) + sorted((ROOT / "scripts").glob("*.py"))
                 + sorted((ROOT / "configs").glob("*.json")) + sorted((ROOT / "notebooks").glob("*.py"))
                 + sorted((ROOT / "docs").glob("*.json"))
                 + [p for p in sorted((ROOT / "docs" / "figures").glob("*.png")) if p.stat().st_size < 400_000])
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(f, f.relative_to(ROOT).as_posix())
    return base64.b64encode(buf.getvalue()).decode("ascii")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--user", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--gpu", action="store_true")
    ap.add_argument("--payload", default="full", choices=["full", "report"], help="files embedded in the kernel")
    ap.add_argument("--sequential", action="store_true", help="run the :: separated commands one after another")
    ap.add_argument("--kernel-sources", nargs="*", default=[], help="other kernels whose output is mounted as input")
    ap.add_argument("--dataset-sources", nargs="*", default=[])
    ap.add_argument("cmd", nargs=argparse.REMAINDER)
    args = ap.parse_args()
    tokens = args.cmd[1:] if args.cmd and args.cmd[0] == "--" else args.cmd
    commands, cur = [], []
    for t in tokens:
        if t == "::":
            commands.append(cur)
            cur = []
        else:
            cur.append(t)
    commands.append(cur)

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "run.py").write_text(TEMPLATE.format(payload=payload(args.payload), commands=commands, sequential=args.sequential),
                                     encoding="utf-8")
    meta = {
        "id": f"{args.user}/{args.name}",
        "title": args.name,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": bool(args.gpu),
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": args.dataset_sources,
        "competition_sources": ["filament-segmentation-2026"],
        "kernel_sources": args.kernel_sources,
        "model_sources": [],
    }
    (args.out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    for c in commands:
        print("staged:", " ".join(c))


if __name__ == "__main__":
    main()
